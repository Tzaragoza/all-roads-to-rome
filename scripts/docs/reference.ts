const effectStr = (e: EventEffect): string => {
  switch (e.type) {
    case 'cut': return `cut ${e.mode}`;
    case 'yield': return `yield ×${e.glory} glory, ×${e.income} denarii`;
    case 'toll': return `toll +${e.surcharge} for ${e.duration} turns`;
    case 'boom': return `boom +${e.value}★`;
  }
};

/**
 * Exact expected count per day of each event kind, from the budget, the weights and the
 * per-day caps (enumerates every pick sequence). Ignores the rare slot skipped for lack of a
 * free turn, which only threats can hit.
 */
function expectedCounts(): Map<string, { mean: number; pAny: number }> {
  const out = new Map<string, { mean: number; pAny: number }>();
  for (const tone of TONES) {
    const specs = EVENTS.filter((e) => e.tone === tone);
    const [lo, hi] = rng(DEFAULT_GEN.budget, tone);
    const acc = new Map(specs.map((s) => [s.kind, { mean: 0, pAny: 0 }]));
    const walk = (left: number, used: Map<string, number>, p: number) => {
      const pool = specs.filter((s) => (used.get(s.kind) ?? 0) < s.gen.maxPerDay);
      if (!left || !pool.length) {
        for (const s of specs) { const n = used.get(s.kind) ?? 0; const a = acc.get(s.kind)!; a.mean += p * n; if (n) a.pAny += p; }
        return;
      }
      const total = pool.reduce((t, s) => t + s.gen.weight, 0);
      for (const s of pool) walk(left - 1, new Map(used).set(s.kind, (used.get(s.kind) ?? 0) + 1), (p * s.gen.weight) / total);
    };
    for (let n = lo; n <= hi; n++) walk(n, new Map(), 1 / (hi - lo + 1));
    for (const [k, v] of acc) out.set(k, v);
  }
  return out;
}

function benchmarkEvidence(): { date: string; byTitle: Map<string, { pass: boolean; evidence: string }> } {
  const byTitle = new Map<string, { pass: boolean; evidence: string }>();
  if (!existsSync('docs/decrees-benchmark.md')) return { date: 'never run', byTitle };
  const md = readFileSync('docs/decrees-benchmark.md', 'utf8');
  const date = /on (\d{4}-\d{2}-\d{2})/.exec(md)?.[1] ?? 'unknown date';
  for (const sec of md.split(/^## /m).slice(1)) {
    const title = /^(.+?) \(/.exec(sec)?.[1];
    if (!title) continue;
    byTitle.set(title, { pass: /\)\s*PASS/.test(sec.split('\n')[0]!), evidence: /\*Evidence:\*\s*(.+)/.exec(sec)?.[1]?.trim() ?? '' });
  }
  return { date, byTitle };
}

